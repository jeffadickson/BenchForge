"""Compiled development workflow boundary and subprocess regressions for batch 200."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from workflow_recorder import recording_host

ROOT = Path(__file__).resolve().parents[2]
SHELL = 'powershell' if os.name == 'nt' else 'pwsh'

class DeveloperBatch200Tests(unittest.TestCase):
    """Use disposable subprocess recorders rather than building application projects."""
    @classmethod
    def setUpClass(cls):
        """Locate the already-built host using the architecture-only bootstrap."""
        result = subprocess.run([SHELL,'-NoProfile','-File',str(ROOT/'build.ps1'),'-PlanOnly'],capture_output=True,text=True,check=True,timeout=60)
        cls.recorder=recording_host()
        cls.dll=ROOT/'.tools/check-workflow'/json.loads(result.stdout.lstrip('\ufeff'))['cache_segment']/'bin/BenchForge.CheckWorkflow.dll'
    def setUp(self):
        """Create a private project tree and recording subprocesses for each case."""
        self.temp=tempfile.TemporaryDirectory(prefix='developer batch ',dir=ROOT/'build')
        self.root=Path(self.temp.name)
        self.project('src/App/App.csproj'); self.project('tests/Core/Core.csproj')
        recorder="import sys,json,pathlib,time\np=pathlib.Path('events.jsonl')\nwith p.open('a') as f:f.write(json.dumps(sys.argv)+'\\n')\nif pathlib.Path('sleep').exists():time.sleep(30)\nstage=pathlib.Path(sys.argv[0]).name\nsys.exit(int(pathlib.Path('fail-'+stage).read_text()) if pathlib.Path('fail-'+stage).exists() else 0)\n"
        for name in ['scripts/check_instrument_catalog.py']:
            path=self.root/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(recorder)
    def tearDown(self):
        """Remove only the disposable tree owned by this test."""
        self.temp.cleanup()
    def project(self,name):
        """Create one project placeholder without invoking MSBuild."""
        path=self.root/name;path.parent.mkdir(parents=True,exist_ok=True);path.touch();return path
    def invoke(self,*args,expected=0):
        """Run the actual compiled command and preserve all diagnostic output."""
        result=subprocess.run(['dotnet',str(self.dll),'--root',str(self.root),'--python',sys.executable,'--dotnet',self.recorder,'--timeout-seconds','5',*args],capture_output=True,text=True,timeout=60)
        self.assertEqual(expected,result.returncode,result.stdout+result.stderr);return result
    def plan(self,task='build',*args):
        """Read a task plan without executing its child programs."""
        return json.loads(self.invoke('--command','plan','--task',task,*args).stdout)
    def events(self):
        """Read exact child argument lists from the private recorder."""
        path=self.root/'events.jsonl';return [json.loads(s) for s in path.read_text().splitlines()] if path.exists() else []
    def report(self):
        """Read the structured developer result generated by the real host."""
        return json.loads((self.root/'build/developer-workflow.json').read_text())

    def test_missing_optional(self):
        """Plan builds without optional example tool or generated folders."""
        self.assertEqual(4,len(self.plan()))

    def test_generation_order(self):
        """Validate catalog before both generators."""
        steps=self.plan('generate');self.assertEqual('scripts/check_instrument_catalog.py',steps[0]['Arguments'][0]);self.assertIn('--preview-v2',steps[2]['Arguments'])

    def test_nested_projects(self):
        """Discover nested application projects."""
        self.project('src/group/Nested/Nested.csproj');self.assertTrue(any('src/group/Nested/Nested.csproj' in s['Arguments'] for s in self.plan()))

    def test_bin_pruned(self):
        """Exclude projects under binary artifact trees."""
        self.project('src/App/bin/Hidden.csproj');self.assertFalse(any('Hidden.csproj' in a for s in self.plan() for a in s['Arguments']))

    def test_obj_pruned(self):
        """Exclude projects under intermediate artifact trees."""
        self.project('src/App/obj/Hidden.csproj');self.assertFalse(any('Hidden.csproj' in a for s in self.plan() for a in s['Arguments']))

    def test_mixed_bin(self):
        """Exclude mixed-case binary artifact folders."""
        self.project('src/App/BiN/Hidden.csproj');self.assertEqual(4,len(self.plan()))

    def test_mixed_obj(self):
        """Exclude mixed-case intermediate artifact folders."""
        self.project('src/App/ObJ/Hidden.csproj');self.assertEqual(4,len(self.plan()))

    def test_browser_excluded(self):
        """Keep browser projects outside ordinary tests."""
        self.project('tests/BenchDouble.Browser.Tests/BenchDouble.Browser.Tests.csproj');self.assertEqual(4,len(self.plan('test')))

    def test_browser_casing(self):
        """Keep differently cased browser projects outside ordinary tests."""
        self.project('tests/browser/benchdouble.browser.tests.csproj');self.assertEqual(4,len(self.plan('test')))

    def test_ordinary_browser_name(self):
        """Retain ordinary tests with Browser in their name."""
        self.project('tests/BrowserHelpers/BrowserHelpers.csproj');self.assertEqual(5,len(self.plan('test')))

    def test_stable_order(self):
        """Sort projects deterministically within a source tree."""
        self.project('src/Z/Z.csproj');self.project('src/A/A.csproj');self.assertEqual(['src/A/A.csproj','src/App/App.csproj','src/Z/Z.csproj'],[s['Arguments'][1] for s in self.plan()[3:]])

    def test_space_paths(self):
        """Preserve project paths containing spaces as one argument."""
        self.project('src/with space/My App.csproj');self.assertTrue(any('src/with space/My App.csproj' in s['Arguments'] for s in self.plan()))

    def test_unicode_paths(self):
        """Preserve Unicode project filenames."""
        self.project('src/meter/æ¸¬å®š.csproj');self.assertTrue(any('src/meter/æ¸¬å®š.csproj' in s['Arguments'] for s in self.plan()))

    def test_no_plan_children(self):
        """Plan mode launches no task subprocesses."""
        self.plan();self.assertEqual([],self.events())

    def test_no_plan_report(self):
        """Plan mode does not create an execution report."""
        self.plan();self.assertFalse((self.root/'build/developer-workflow.json').exists())

    def test_preserve_plan_report(self):
        """Plan mode preserves a prior execution report."""
        path=self.root/'build/developer-workflow.json';path.parent.mkdir();path.write_text('prior');self.plan();self.assertEqual('prior',path.read_text())

    def test_debug_configuration(self):
        """Forward Debug configuration to every dotnet task."""
        steps=self.plan('build','--configuration','Debug');self.assertTrue(all('Debug' in s['Arguments'] for s in steps[1:]))

    def test_release_configuration(self):
        """Use Release for default developer tasks."""
        self.assertTrue(all('Release' in s['Arguments'] for s in self.plan()[1:]))

    def test_reject_configuration(self):
        """Reject unknown configurations before launching tasks."""
        self.invoke('--command','build','--configuration','invalid',expected=2);self.assertEqual([],self.events())

    def test_filter_argument(self):
        """Forward a compound test filter as one argument."""
        value='FullyQualifiedName~Clock|FullyQualifiedName~Mock';steps=self.plan('test','--test-filter',value);self.assertEqual(['--filter',value],steps[-1]['Arguments'][-2:])

    def test_filter_spaces(self):
        """Preserve test filter spaces without token splitting."""
        value='DisplayName=some test name';self.assertEqual(value,self.plan('test','--test-filter',value)[-1]['Arguments'][-1])

    def test_filter_metacharacters(self):
        """Preserve filter shell metacharacters literally."""
        value='Name=x; echo never';self.assertEqual(value,self.plan('test','--test-filter',value)[-1]['Arguments'][-1]);self.assertEqual([],self.events())

    def test_filter_not_generation(self):
        """Do not apply test filters to generation."""
        steps=self.plan('generate','--test-filter','Name=x');self.assertFalse(any('--filter' in s['Arguments'] for s in steps))

    def test_filter_not_build(self):
        """Do not apply test filters to builds."""
        steps=self.plan('build','--test-filter','Name=x');self.assertFalse(any('--filter' in s['Arguments'] for s in steps))

    def test_empty_filter(self):
        """Omit empty test filters."""
        self.assertNotIn('--filter',self.plan('test')[-1]['Arguments'])

    def test_generation_execution(self):
        """Execute exactly the catalog and two generation steps."""
        self.invoke('--command','generate');self.assertEqual(3,len(self.events()));self.assertEqual(3,len(self.report()['stages']))

    def test_build_execution(self):
        """Build source projects only after generation."""
        self.invoke('--command','build');self.assertEqual(['check_instrument_catalog.py','run','run','build'],[Path(e[0]).name for e in self.events()])

    def test_test_execution(self):
        """Run test projects only after generation."""
        self.invoke('--command','test');self.assertEqual('test',self.events()[-1][0]);self.assertEqual('test',self.report()['task'])

    def test_catalog_failure(self):
        """Stop before generators after catalog failure."""
        (self.root/'fail-check_instrument_catalog.py').write_text('23');self.invoke('--command','build',expected=23);self.assertEqual(1,len(self.events()));self.assertEqual(23,self.report()['stages'][0]['ExitCode'])

    def test_generator_failure(self):
        """Stop before preview generation after generator failure."""
        (self.root/'fail-run').write_text('24');self.invoke('--command','build',expected=24);self.assertEqual(2,len(self.events()));self.assertEqual(24,self.report()['stages'][-1]['ExitCode'])

    def test_build_failure(self):
        """Preserve the first failing build exit code."""
        self.project('src/Z/Z.csproj');(self.root/'fail-build').write_text('25');self.invoke('--command','build',expected=25);self.assertEqual(4,len(self.events()));self.assertEqual(25,self.report()['stages'][-1]['ExitCode'])

    def test_test_failure(self):
        """Stop later test projects after a failure."""
        self.project('tests/Z/Z.csproj');(self.root/'fail-test').write_text('26');self.invoke('--command','test',expected=26);self.assertEqual(4,len(self.events()));self.assertEqual(26,self.report()['stages'][-1]['ExitCode'])

    def test_duration_report(self):
        """Record nonnegative stage durations on success."""
        self.invoke('--command','generate');self.assertTrue(all(s['Milliseconds']>=0 for s in self.report()['stages']))

    def test_executable_report(self):
        """Record selected executable identities."""
        self.invoke('--command','generate');stages=self.report()['stages'];self.assertEqual(sys.executable,stages[0]['Executable']);self.assertTrue(all(s['Executable']==self.recorder for s in stages[1:]))

    def test_arguments_report(self):
        """Record exact generator arguments."""
        self.invoke('--command','generate');self.assertEqual('--preview-v2',self.report()['stages'][2]['Arguments'][6])

    def test_timeout(self):
        """Terminate timed-out children before dependent work."""
        (self.root/'sleep').touch();host=['dotnet',str(self.dll),'--root',str(self.root),'--python',sys.executable,'--dotnet',self.recorder,'--command','build','--timeout-seconds','1'];r=subprocess.run(host,capture_output=True,text=True,timeout=30);self.assertEqual(124,r.returncode,r.stderr);self.assertEqual(1,len(self.events()));self.assertEqual(124,self.report()['stages'][0]['ExitCode'])

    def test_missing_python(self):
        """Record missing catalog executable without invoking dotnet tasks."""
        r=subprocess.run(['dotnet',str(self.dll),'--root',str(self.root),'--python',str(self.root/'missing.exe'),'--command','build'],capture_output=True,text=True,timeout=30);self.assertEqual(2,r.returncode);self.assertEqual(2,self.report()['stages'][0]['ExitCode']);self.assertEqual([],self.events())

    def test_unknown_task(self):
        """Reject unsupported task names before launching work."""
        self.invoke('--command','plan','--task','unknown',expected=2);self.assertEqual([],self.events())

    def test_unknown_option(self):
        """Reject unsupported workflow options."""
        self.invoke('--command','build','--unknown','x',expected=2);self.assertEqual([],self.events())

    def test_duplicate_option(self):
        """Reject duplicate command options."""
        self.invoke('--command','build','--command','test',expected=2);self.assertEqual([],self.events())

    def directory_link(self,link,target):
        """Create a private directory link; Windows junctions need no developer-mode privileges."""
        if os.name=='nt':
            result=subprocess.run(['cmd','/c','mklink','/J',str(link),str(target)],capture_output=True,text=True,timeout=30)
            self.assertEqual(0,result.returncode,result.stdout+result.stderr)
        else:
            os.symlink(target,link,target_is_directory=True)

    def test_linked_project_directory(self):
        """Linked project directories cannot pull unrelated projects into a build."""
        target=self.root/'outside';self.project('outside/Hidden.csproj')
        self.directory_link(self.root/'src'/'linked',target)
        self.assertEqual(4,len(self.plan()))

    def test_linked_source_root(self):
        """A linked source root is excluded before project enumeration."""
        source=self.root/'src';target=self.root/'outside'
        source.rename(target)
        self.directory_link(source,target)
        self.assertEqual(3,len(self.plan()))

    def test_link_cycle(self):
        """A directory link cycle never starts recursive project traversal."""
        self.directory_link(self.root/'src'/'App'/'cycle',self.root/'src')
        self.assertEqual(4,len(self.plan()))
