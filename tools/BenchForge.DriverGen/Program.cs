    body.AppendLine("  /// <param name=\"role\">Logical bench role identifier.</param>");
    body.AppendLine("  /// <param name=\"backend\">Explicit backend provenance.</param>");
    body.AppendLine("  /// <param name=\"calibration\">Optional calibration certificate metadata.</param>");
    body.AppendLine("  /// <returns>Canonical <see cref=\"IBenchInstrument\"/> wrapper.</returns>");
    body.AppendLine($"  public IBenchInstrument AsBenchInstrument(string role, InstrumentBackend backend = InstrumentBackend.Physical, InstrumentCalibrationInfo? calibration = null) =>");
    body.AppendLine($"    new GeneratedBenchInstrument(role, {JsonSerializer.Serialize(name)}, \"SCPI\", [{capList}], backend, calibration);");
    if (HasR("DcVoltage", "ElectricPotential") && HasR("DcCurrent", "ElectricCurrent") && HasR("Resistance", "ElectricResistance"))
    {
        body.AppendLine($"  /// <summary>Wrap this {name} driver as a symmetric <see cref=\"IBenchDigitalMultimeter\"/> for <see cref=\"BenchForge.Client.BenchSession\"/>.</summary>");
        body.AppendLine("  /// <param name=\"role\">Logical bench role identifier.</param>");
        body.AppendLine("  /// <param name=\"backend\">Explicit backend provenance.</param>");
        body.AppendLine("  /// <param name=\"calibration\">Optional calibration certificate metadata.</param>");
        body.AppendLine("  /// <returns>Symmetric <see cref=\"IBenchDigitalMultimeter\"/> adapter.</returns>");
        body.AppendLine($"  public IBenchDigitalMultimeter AsBenchDmm(string role, InstrumentBackend backend = InstrumentBackend.Physical, InstrumentCalibrationInfo? calibration = null) =>");
        body.AppendLine($"    new GeneratedBenchDmm(role, {JsonSerializer.Serialize(name)}, ct => TryGetDcVoltageAsync(1, ct), ct => TryGetDcCurrentAsync(1, ct), ct => TryGetResistanceAsync(1, ct), backend, calibration);");
    }
    string? voltParam = HasRW("SourceVoltage", "ElectricPotential") ? "SourceVoltage"
        : HasRW("Voltage", "ElectricPotential") ? "Voltage" : null;
    string? currLimitParam = HasRW("CurrentLimit", "ElectricCurrent") ? "CurrentLimit"
        : HasRW("CurrentCompliance", "ElectricCurrent") ? "CurrentCompliance" : null;
    if (voltParam is not null && currLimitParam is not null && HasR("MeasuredVoltage", "ElectricPotential") && HasR("MeasuredCurrent", "ElectricCurrent"))
    {
        body.AppendLine($"  /// <summary>Wrap this {name} driver as a symmetric <see cref=\"IBenchPowerSupply\"/> for <see cref=\"BenchForge.Client.BenchSession\"/>.</summary>");
        body.AppendLine("  /// <param name=\"role\">Logical bench role identifier.</param>");
        body.AppendLine("  /// <param name=\"backend\">Explicit backend provenance.</param>");
        body.AppendLine("  /// <param name=\"calibration\">Optional calibration certificate metadata.</param>");
        body.AppendLine("  /// <returns>Symmetric <see cref=\"IBenchPowerSupply\"/> adapter.</returns>");
        body.AppendLine($"  public IBenchPowerSupply AsBenchPowerSupply(string role, InstrumentBackend backend = InstrumentBackend.Physical, InstrumentCalibrationInfo? calibration = null) =>");
        body.AppendLine($"    new GeneratedBenchPowerSupply(role, {JsonSerializer.Serialize(name)}, session, (ch, v, ct) => TrySet{voltParam}Async(ch, v, ct), (ch, ct) => TryGet{voltParam}Async(ch, ct), (ch, i, ct) => TrySet{currLimitParam}Async(ch, i, ct), (ch, ct) => TryGet{currLimitParam}Async(ch, ct), (ch, ct) => TryGetMeasuredVoltageAsync(ch, ct), (ch, ct) => TryGetMeasuredCurrentAsync(ch, ct), backend, calibration);");
    }
    if (HasW("SetpointTemperature", "Temperature") && HasR("MeasuredTemperature", "Temperature"))
    {
        body.AppendLine($"  /// <summary>Wrap this {name} driver as a symmetric <see cref=\"IBenchThermalController\"/> for <see cref=\"BenchForge.Client.BenchSession\"/>.</summary>");
        body.AppendLine("  /// <param name=\"role\">Logical bench role identifier.</param>");
        body.AppendLine("  /// <param name=\"backend\">Explicit backend provenance.</param>");
        body.AppendLine("  /// <param name=\"calibration\">Optional calibration certificate metadata.</param>");
