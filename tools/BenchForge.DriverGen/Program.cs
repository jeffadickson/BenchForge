            if (param.TryGetProperty("maximum", out var max)) body.AppendLine($"    if (number > {max.GetDouble().ToString("R", System.Globalization.CultureInfo.InvariantCulture)}) throw new ArgumentOutOfRangeException(nameof(value));");
            body.AppendLine("    string encoded = number.ToString(\"G17\", CultureInfo.InvariantCulture);");
            body.AppendLine($"    await session.WriteAsync($\"{set.Replace("{value}", "{encoded}")}\", ct).ConfigureAwait(false);");
            body.AppendLine("  }");
            body.AppendLine($"  /// <summary>Railroad-oriented write for {propertyName} in {unit}, returning a typed <see cref=\"BenchResult\"/> instead of throwing on operational faults.</summary>");
            body.AppendLine($"  /// <param name=\"channel\">One-based channel, 1 through {channelCount}.</param>");
            body.AppendLine($"  /// <param name=\"value\">Finite {quantity} validated against the definition limits.</param>");
            body.AppendLine("  /// <param name=\"ct\">Cancellation forwarded to the transport; cancellation after dispatch leaves physical state uncertain.</param>");
            body.AppendLine("  /// <returns>Railroad outcome indicating write acceptance or a structured <see cref=\"BenchError\"/>.</returns>");
            body.AppendLine($"  public ValueTask<BenchResult> TrySet{propertyName}Async(int channel, {quantity} value, CancellationToken ct = default) =>");
            body.AppendLine($"    GeneratedDriverRailroad.ExecuteWriteAsync({Literal(name)}, {Literal(propertyName)}, () => Set{propertyName}Async(channel, value, ct));");
        }
        // Generated typed mock configuration; the same quantity/unit mapping
        // is used by the typed driver and the SCPI mock session.
        mockMethods.AppendLine($"  /// <summary>Configure the simulated {propertyName} reading without sending hardware commands.</summary>");
        mockMethods.AppendLine($"  /// <param name=\"channel\">One-based channel, 1 through {channelCount}.</param>");
        mockMethods.AppendLine($"  /// <param name=\"value\">Finite {quantity}, converted to {unit} and validated against the definition limits.</param>");
        mockMethods.AppendLine("  /// <exception cref=\"ArgumentOutOfRangeException\">Channel or value violates the definition.</exception>");
        mockMethods.AppendLine($"  public void SetMock{propertyName}(int channel, {quantity} value)");
        mockMethods.AppendLine("  {");
        string mockValueExpr = info.isDecimal ? $"(double)value.{info.unitProperty}" : $"value.{info.unitProperty}";
        mockMethods.AppendLine($"    SetReading({Literal(propertyName)}, channel, {mockValueExpr});");
        mockMethods.AppendLine("  }");
    }
