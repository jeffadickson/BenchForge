            body.AppendLine("  /// <param name=\"ct\">Cancellation forwarded to the transport.</param>");
            body.AppendLine($"  /// <returns>Railroad outcome containing the typed {quantity} or a structured <see cref=\"BenchError\"/>.</returns>");
