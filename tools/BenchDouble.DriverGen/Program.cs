using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

if (args.Length is < 2 or > 3 || (args.Length == 3 && args[2] != "--check"))
{
    Console.Error.WriteLine("Usage: BenchDouble.DriverGen <instrument-definitions-directory> <output-directory> [--check]");
    return 2;
}
bool checkOnly = args.Length == 3;
var input = Path.GetFullPath(args[0]);
var output = Path.GetFullPath(args[1]);
if (!Directory.Exists(input)) { Console.Error.WriteLine("Definitions folder not found."); return 2; }
if (!checkOnly) Directory.CreateDirectory(output);
int generated = 0;
foreach (var file in Directory.EnumerateFiles(input, "*.instrument.json", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
{
    using var document = JsonDocument.Parse(File.ReadAllText(file));
    var root = document.RootElement;
    if (root.GetProperty("schemaVersion").GetInt32() != 1) throw new InvalidDataException($"Unsupported schema: {file}");
    string name = root.GetProperty("driverName").GetString() ?? "";
    if (!Regex.IsMatch(name, @"^[A-Za-z_][A-Za-z0-9_]*$")) throw new InvalidDataException($"Invalid class name in {file}");
    int channelCount = root.TryGetProperty("channels", out var channels) &&
        channels.TryGetProperty("count", out var count) ? count.GetInt32() : 1;
    if (channelCount < 1 || channelCount > 256)
        throw new InvalidDataException($"Invalid channel count: {file}");
    var parameters = root.GetProperty("parameters").EnumerateArray().ToArray();
    if (parameters.Length == 0 || parameters.Length > 512)
        throw new InvalidDataException($"Invalid parameter count: {file}");
    var seen = new HashSet<string>(StringComparer.Ordinal);
    var mock = new StringBuilder();
    mock.AppendLine("// <auto-generated />");
    mock.AppendLine("// Definition-driven SCPI mock: same metadata as the typed driver.");
    mock.AppendLine("using BenchDouble.Simulation;");
    mock.AppendLine("using UnitsNet;");
    mock.AppendLine("namespace BenchDouble.Generated;");
    mock.AppendLine($"public sealed class {name}Mock : DefinitionDrivenScpiMockSession");
    mock.AppendLine("{");
    mock.AppendLine($"  public {name}Mock() : base({channelCount}, new MockScpiParameter[]");
    mock.AppendLine("  {");
    var mockMethods = new StringBuilder();
    var body = new StringBuilder();
    body.AppendLine("// <auto-generated />");
    body.AppendLine("// Generated from an instrument description. Do not edit directly.");
    body.AppendLine("using System.Globalization;");
    body.AppendLine("using BenchDouble.Async;");
    body.AppendLine("using UnitsNet;");
    body.AppendLine("namespace BenchDouble.Generated;");
    body.AppendLine($"public sealed partial class {name}(IAsyncScpiSession session)");
    body.AppendLine("{");
    foreach (var param in parameters)
    {
        string propertyName = param.GetProperty("name").GetString() ?? "";
        string quantity = param.GetProperty("quantity").GetString() ?? "";
        string unit = param.GetProperty("unit").GetString() ?? "";
        string query = param.TryGetProperty("query", out var q) ? q.GetString() ?? "" : "";
        string set = param.TryGetProperty("set", out var st) ? st.GetString() ?? "" : "";
        if (!Regex.IsMatch(propertyName, @"^[A-Za-z_][A-Za-z0-9_]*$") ||
            !seen.Add(propertyName)) throw new InvalidDataException($"Invalid or duplicate parameter {file}");
        // Strict allow-list prevents arbitrary C# expressions in schema values.
        var units = new Dictionary<string, (string unitProperty, string factory)>(StringComparer.Ordinal)
        {
            ["Frequency:Hertz"] = ("Hertz", "FromHertz"),
            ["ElectricPotential:Volt"] = ("Volts", "FromVolts"),
            ["ElectricResistance:Ohm"] = ("Ohms", "FromOhms"),
            ["ElectricCurrent:Ampere"] = ("Amperes", "FromAmperes")
        };
        if (!units.TryGetValue($"{quantity}:{unit}", out var info)) throw new InvalidDataException($"Unsupported quantity/unit: {quantity}/{unit}");
        foreach (var template in new[] { query, set }.Where(t => t.Length > 0))
        {
            if (!Regex.IsMatch(template, @"^[A-Za-z0-9_:+? .{}-]+$") ||
                template.Replace("{channel}", "").Replace("{value}", "").Contains('{') ||
                template.Replace("{channel}", "").Replace("{value}", "").Contains('}'))
                throw new InvalidDataException($"Unsupported command template in {file}");
        }
        if (query.Length == 0 && set.Length == 0)
            throw new InvalidDataException($"Parameter {propertyName} needs a query or setter.");
        if (channelCount > 1 &&
            (query.Length > 0 && !query.Contains("{channel}", StringComparison.Ordinal) ||
             set.Length > 0 && !set.Contains("{channel}", StringComparison.Ordinal)))
            throw new InvalidDataException($"Multi-channel command for {propertyName} lacks channel placeholder.");
        double? minimum = param.TryGetProperty("minimum", out var minValue) ? minValue.GetDouble() : null;
        double? maximum = param.TryGetProperty("maximum", out var maxValue) ? maxValue.GetDouble() : null;
        double initial = param.TryGetProperty("mock", out var mockNode) &&
            mockNode.TryGetProperty("defaultValue", out var mockValue)
            ? mockValue.GetDouble() : minimum is { } lower ? Math.Max(0, lower) : 0;
        if (!double.IsFinite(initial) ||
            (minimum is { } finiteMin && !double.IsFinite(finiteMin)) ||
            (maximum is { } finiteMax && !double.IsFinite(finiteMax)) ||
            (minimum is { } lo && initial < lo) ||
            (maximum is { } hi && initial > hi) ||
            (minimum is { } minBound && maximum is { } maxBound && minBound > maxBound))
            throw new InvalidDataException($"Invalid mock default or range for {propertyName}: {file}");
        static string Literal(string value) => JsonSerializer.Serialize(value);
        static string Number(double value) =>
            value.ToString("R", System.Globalization.CultureInfo.InvariantCulture);
        mock.AppendLine($"    new MockScpiParameter({Literal(propertyName)}, {Literal(quantity)}, " +
            $"{Literal(unit)}, {(query.Length == 0 ? "null" : Literal(query))}, " +
            $"{(set.Length == 0 ? "null" : Literal(set))}, {Number(initial)}, " +
            $"{(minimum.HasValue ? Number(minimum.Value) : "null")}, " +
            $"{(maximum.HasValue ? Number(maximum.Value) : "null")}),");
        mock.AppendLine($"    // {propertyName}: {quantity} in {unit}");
        if (query.Length > 0)
        {
            if (query.Contains("{value}")) throw new InvalidDataException("Query may not contain {value}.");
            body.AppendLine($"  public async ValueTask<{quantity}> Get{propertyName}Async(int channel, CancellationToken ct = default)");
            body.AppendLine("  {");
            body.AppendLine($"    if (channel < 1 || channel > {channelCount}) throw new ArgumentOutOfRangeException(nameof(channel));");
            body.AppendLine($"    string reply = await session.QueryAsync($\"{query.Replace("{channel}", "{channel}")}\", ct).ConfigureAwait(false);");
            body.AppendLine($"    return {quantity}.{info.factory}(double.Parse(reply, NumberStyles.Float, CultureInfo.InvariantCulture));");
            body.AppendLine("  }");
        }
        if (set.Length > 0)
        {
            if (!set.Contains("{value}")) throw new InvalidDataException("Setter must contain {value}.");
            body.AppendLine($"  public async ValueTask Set{propertyName}Async(int channel, {quantity} value, CancellationToken ct = default)");
            body.AppendLine("  {");
            body.AppendLine($"    if (channel < 1 || channel > {channelCount}) throw new ArgumentOutOfRangeException(nameof(channel));");
            body.AppendLine($"    double number = value.{info.unitProperty};");
            body.AppendLine("    if (!double.IsFinite(number)) throw new ArgumentOutOfRangeException(nameof(value));");
            if (param.TryGetProperty("minimum", out var min)) body.AppendLine($"    if (number < {min.GetDouble().ToString("R", System.Globalization.CultureInfo.InvariantCulture)}) throw new ArgumentOutOfRangeException(nameof(value));");
            if (param.TryGetProperty("maximum", out var max)) body.AppendLine($"    if (number > {max.GetDouble().ToString("R", System.Globalization.CultureInfo.InvariantCulture)}) throw new ArgumentOutOfRangeException(nameof(value));");
            body.AppendLine("    string encoded = number.ToString(\"G17\", CultureInfo.InvariantCulture);");
            body.AppendLine($"    await session.WriteAsync($\"{set.Replace("{value}", "{encoded}")}\", ct).ConfigureAwait(false);");
            body.AppendLine("  }");
        }
        // Generated typed mock configuration; the same quantity/unit mapping
        // is used by the typed driver and the SCPI mock session.
        mockMethods.AppendLine($"  public void SetMock{propertyName}(int channel, {quantity} value)");
        mockMethods.AppendLine("  {");
        mockMethods.AppendLine($"    SetReading({Literal(propertyName)}, channel, value.{info.unitProperty});");
        mockMethods.AppendLine("  }");
    }
    body.AppendLine("}");
    var destination = Path.Combine(output, name + ".g.cs");
    var source = body.ToString().Replace("\r\n", "\n");
    if (checkOnly)
    {
        if (!File.Exists(destination) || File.ReadAllText(destination) != source)
            throw new InvalidDataException($"Generated driver is stale: {destination}");
    }
    else if (!File.Exists(destination) || File.ReadAllText(destination) != source)
        File.WriteAllText(destination, source, new UTF8Encoding(false));
    mock.AppendLine("  }) { }");
    mock.Append(mockMethods);
    mock.AppendLine($"  public {name} CreateDriver() => new(this);");
    mock.AppendLine("}");
    var mockDestination = Path.Combine(output, name + "Mock.g.cs");
    var mockSource = mock.ToString().Replace("\r\n", "\n");
    if (checkOnly)
    {
        if (!File.Exists(mockDestination) || File.ReadAllText(mockDestination) != mockSource)
            throw new InvalidDataException($"Generated mock is stale: {mockDestination}");
    }
    else if (!File.Exists(mockDestination) || File.ReadAllText(mockDestination) != mockSource)
        File.WriteAllText(mockDestination, mockSource, new UTF8Encoding(false));
    Console.WriteLine($"Generated {destination} and {mockDestination}");
    generated++;
}
Console.WriteLine($"{(checkOnly ? "Verified" : "Generated")} {generated} typed driver/mock pair(s).");
return 0;
